SELECT
    t.id,
    t.orgId,
    t.lineId,
    t.orderNo,
    t.poNumber,
    t.orderStatus,
    t.channelId,
    t.channel,
    t.channelFlag,
    t.amount,
    t.shippingFee,
    t.estimateTotalCost,
    t.labelAfterPacking,
    t.currencyCode,
    t.fulfillmentChannel,
    t.orgWarehouseId,
    t.orgWarehouseCode,
    t.shippingMethodCode,
    t.realShippingMethodCode,
    t.carrierAccountGroupId,
    t.shipmentType,
    t.orderType,
    t.isPrime,
    t.isBusinessOrder,
    t.isCelebrity,
    t.isSample,
    t.isReshipment,
    t.isAddition,
    t.isDismantlement,
    t.isActive,
    t.isArtificial,
    t.isOnsite,
    t.parentId,
    t.orderClass,
    t.errorCode,
    t.systemShipServiceLevel,
    t.carrier,
    t.state,
    t.zone,
    t.customerName,
    t.customerCode,
    t.addressType,
    t.shippingName,
    t.customerId,
    t.salespersonId,
    t.shipTo,
    t.billTo,
    t.referenceNo,
    t.invoiceNo,
    t.carrierAddition,
    t.shippingFeeCurrency,
    t.paymentMethod,
    t.sellerSku,
    t.quantity,
    t.erpSku,
    t.parentSku,
    t.asin,
    t.isGift,
    t.deliveryOrderCode,
    t.payNo,
    CASE
        WHEN IFNULL(t.trackNo,'') != '' THEN t.trackNo
        WHEN IFNULL(t.trackNoBak,'') != '' THEN t.trackNoBak
        WHEN IFNULL(t.trackNoBak2,'') != '' THEN t.trackNoBak2
        ELSE ''
        END AS trackNo,
    t.isShip,
    t.promotionIds,
    t.itemAmount,
    t.promotionDiscountPrice,
    t.subLineId,
    t.skuName,
    t.latestShipDate,
    t.channelCreated,
    t.shipmentDate,
    t.createdAt,
    t.updatedAt,
    t.warehouseExpectedShipDate,
    t.disabledAt,
    t.logisticStatus,
    t.labelIds,
    IFNULL(t.urgentOrder,0) AS urgentOrder,
    IFNULL(t.platformShippingType,2) AS platformShippingType,
    CASE
        WHEN t.isMultiChannel > 0 THEN 1
        ELSE 0
        END AS isMultiChannel,
    CASE
        WHEN t.multiChannelService ='walmart' THEN 'WFS'
        WHEN t.multiChannelService ='wayfair' THEN 'wayfair'
        ELSE ''
        END AS multiChannelService,
    t.purchaser_id AS purchaserId,
    t.b2b_order_status AS b2bOrderStatus,
    "" AS bak2,
    "" AS bak3,
    "" AS bak4,
    "" AS bak5,
    "" AS bak6,
    0 AS status5,
    0 AS status6
FROM(
        SELECT
            so.`id` AS id,
            so.`org_id` AS orgId,
            so.`line_id` AS lineId,
            so.`order_no` AS orderNo,
            so.`po_number` AS poNumber,
            so.`order_status` AS orderStatus,
            so.`channel_id` AS channelId,
            so.`channel` AS channel,
            so.`channel_flag` AS channelFlag,
            so.`amount` AS amount,
            so.`shipping_fee` as shippingFee,
            so.`estimate_total_cost` as estimateTotalCost,
            sod.`label_after_packing` as labelAfterPacking,
            so.`currency_code` AS currencyCode,
            so.`fulfillment_channel` AS fulfillmentChannel,
            so.`org_warehouse_id` AS orgWarehouseId,
            so.`org_warehouse_code` AS orgWarehouseCode,
            so.`shipping_method_code` AS shippingMethodCode,
            sod.`real_shipping_method_code` AS realShippingMethodCode,
            so.`carrier_account_group_id` AS carrierAccountGroupId,
            so.`shipment_type` AS shipmentType,
            so.`order_type` AS orderType,
            so.`is_prime` AS isPrime,
            so.`is_business_order` AS isBusinessOrder,
            so.`is_celebrity` AS isCelebrity,
            so.`is_sample` AS isSample,
            so.`is_reshipment` AS isReshipment,
            so.`is_addition` AS isAddition,
            so.`is_dismantlement` AS isDismantlement,
            so.`is_active` AS isActive,
            so.`is_artificial` AS isArtificial,
            so.`is_gift` AS isGift,
            so.`delivery_order_code` AS deliveryOrderCode,
            so.`pay_no` AS payNo,
            so.`is_onsite` AS isOnsite,
            so.`parent_id` AS parentId,
            so.`order_class` AS orderClass,
            so.`error_code` AS errorCode,
            sod.`system_ship_service_level` AS systemShipServiceLevel,
            sod.`platform_shipping_type` AS platformShippingType,
            sod.`carrier` AS carrier,
            soa.`state` AS state,
            if (min(dos.`warehouse_zone`) is not null, min(dos.`warehouse_zone`), 0) AS zone,
		soa.`address_type` AS addressType,
		so.`shipping_name` AS shippingName,
		so.`customer_id` AS customerId,
		so.`salesperson_id` AS salespersonId,
		so.`ship_to` AS shipTo,
		so.`bill_to` AS billTo,
		sod.`reference_no` AS referenceNo,
		sod.`invoice_no` AS invoiceNo,
		sod.`customer_name` AS customerName,
		sod.`customer_code` AS customerCode,
		sod.`carrier_addition` as carrierAddition,
		sod.`shipping_fee_currency` as shippingFeeCurrency,
		so.`payment_method` AS paymentMethod,
		soi.`seller_sku` AS sellerSku,
		soi.`quantity` AS quantity,
		soi.`erp_sku` AS erpSku,
		GROUP_CONCAT(DISTINCT soip.`parent_sku` SEPARATOR ',') AS parentSku,
		soi.`asin` as asin,
		(SELECT GROUP_CONCAT(DISTINCT ssp.`track_no` SEPARATOR ',') FROM dashboard.`sale_shipment_packages` AS ssp
		 WHERE so.`id` = ssp.`head_id` AND ssp.`disabled_at` = 0 AND ssp.`head_item_id` = soi.`id`) AS trackNo,
		 (SELECT GROUP_CONCAT(DISTINCT ssp.`track_no` SEPARATOR ',') FROM dashboard.`sale_shipment_packages` AS ssp
		 WHERE so.`id` = ssp.`head_id` AND ssp.`disabled_at` = 0 AND ssp.`head_item_id` = 0) AS trackNoBak,
		(SELECT GROUP_CONCAT(DISTINCT ca.`name` SEPARATOR ',') FROM dashboard.`common_attachments` AS ca
		 WHERE so.`id` = ca.`source_id` AND ca.`disabled_at` = 0 AND ca.`type` = 0) AS trackNoBak2,
		soi.`is_ship` AS isShip,
		soi.`promotion_ids` AS promotionIds,
		soi.`item_amount` AS itemAmount,
		soi.`promotion_discount_price` AS promotionDiscountPrice,
		soi.`line_id` AS subLineId,
		soi.`sku_name` As skuName,
		CASE so.`latest_ship_date` WHEN '0000-00-00 00:00:00' THEN NULL ELSE DATE_FORMAT(so.`latest_ship_date`,"%Y-%m-%d %H:%i:%S") END AS latestShipDate,
		CASE so.`channel_created` WHEN '0000-00-00 00:00:00' THEN NULL ELSE DATE_FORMAT(so.`channel_created`,"%Y-%m-%d %H:%i:%S") END AS channelCreated,
		CASE so.`shipment_date` WHEN '0000-00-00 00:00:00' THEN NULL ELSE DATE_FORMAT(so.`shipment_date`,"%Y-%m-%d %H:%i:%S") END AS shipmentDate,
		DATE_FORMAT(so.`created_at`,"%Y-%m-%d %H:%i:%S") AS createdAt,
		DATE_FORMAT(so.`updated_at`,"%Y-%m-%d %H:%i:%S") AS updatedAt,
		DATE_FORMAT(sod.`warehouse_expected_ship_date`,"%Y-%m-%d %H:%i:%S") AS warehouseExpectedShipDate,
		so.`disabled_at` AS disabledAt,
		(SELECT ssp.`logistic_status` FROM dashboard.`sale_shipment_packages` AS ssp
		 WHERE so.`id` = ssp.`head_id` AND ssp.package_flag = 0 AND ssp.disabled_at = 0
				LIMIT 1) AS logisticStatus,
		(SELECT GROUP_CONCAT(sol.`label_id` SEPARATOR ',') FROM dashboard.`sale_order_labels` sol WHERE sol.`head_id` = so.`id`) AS labelIds,
		max(dod.urgent_order) AS urgentOrder,
		(SELECT count(1) FROM dashboard.`wfs_warehouse_channel_mapping` wf WHERE wf.`org_warehouse_id` = so.`org_warehouse_id`) AS isMultiChannel,
		(SELECT platform_type FROM dashboard.`wfs_warehouse_channel_mapping` wf WHERE wf.`org_warehouse_id` = so.`org_warehouse_id` group by wf.`org_warehouse_id`) AS multiChannelService,
		sod.purchaser_id,
		sod.b2b_order_status
        FROM
            sale_order_items AS soi
            LEFT JOIN sale_orders AS so ON so.`id` = soi.`head_id`
            LEFT JOIN deliver_orders AS dos ON so.`id` = dos.`source_id` AND dos.`disabled_at` = 0 AND dos.`deliver_order_status` != 3
            LEFT JOIN deliver_order_details AS dod ON dos.`id` = dod.`head_id` AND dod.`org_id` = dos.`org_id`
            LEFT JOIN sale_order_details AS sod ON so.`id`=sod.`head_id`
            LEFT JOIN sale_order_address AS soa ON so.`id`=soa.`head_id`
            LEFT JOIN sale_order_item_products AS soip ON soi.`id` = soip.`head_item_id`
        where soi.`disabled_at` = 0 AND so.`updated_at` >= DATE_SUB(:sql_last_value, INTERVAL 5 MINUTE)
        GROUP BY soi.`id`
    ) t
